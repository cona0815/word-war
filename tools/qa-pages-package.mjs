import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {buildPages, isPublicFile} from './build-pages.mjs';

const root = await fs.mkdtemp(path.join(os.tmpdir(), 'word-war-package-'));
const strip = 'assets/generated/test/cast-strip.png';
const idle = 'assets/generated/test/idle.png';
const files = ['index.html', 'hero-cast-clips.js', strip, idle];
await fs.mkdir(path.dirname(path.join(root, strip)), {recursive:true});
await fs.writeFile(path.join(root, 'index.html'), '<title>Word War</title>');
await fs.writeFile(path.join(root, 'hero-cast-clips.js'), `window.HeroCastClips={'male:1:test':{url:'${strip}'}};`);
await fs.writeFile(path.join(root, strip), Buffer.from([0, 255, 128, 1]));
await fs.writeFile(path.join(root, idle), Buffer.from([17, 64, 255]));
assert.equal(isPublicFile('assets/generated/hero-weapons/raw.png'), false);
assert.equal(isPublicFile('assets/generated/hero-weapons-normalized-v2/hero.png'), true);
for (const file of ['.env', '.clasp.json', '.deploy-gas/private.js', 'tools/test.js', 'gas_code.gs']) assert.equal(isPublicFile(file), false, file);
const output = path.join(root, 'output');
const result = await buildPages(root, output, files);
assert.equal(result.files, 4);assert.equal(result.clips, 1);
assert.deepEqual(await fs.readFile(path.join(output, strip)), await fs.readFile(path.join(root, strip)));
await assert.rejects(buildPages(root, output, files), /empty/);
await assert.rejects(buildPages(root, root, files), /inside/);
await assert.rejects(buildPages(root, path.join(root, 'bad'), [...files, '../outside.png']), /Unsafe/);
await assert.rejects(buildPages(root, path.join(root, 'missing'), files.filter(file => file !== idle)), /Missing male/);
await fs.writeFile(path.join(root, 'index.html'), '<img src="assets/generated/hero-weapons/raw.png">');
await assert.rejects(buildPages(root, path.join(root, 'reference'), files), /Excluded archive referenced/);
console.log('PASS package byte fidelity, private file exclusions, archive reference guard, missing clip guard and non-destructive output checks');
